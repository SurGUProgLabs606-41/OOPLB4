/**
 * @file PrintedPublication.h
 * @brief Объявление промежуточного класса PrintedPublication.
 *
 * @details
 * Класс представляет печатное библиотечное издание.
 *
 * Реализует следующие требования лабораторной работы:
 *
 * Пункт 1. Второй уровень иерархии наследования.
 * Наследуется от Publication с использованием виртуального наследования.
 *
 * Пункт 3. Переопределяет виртуальную функцию printInfo()
 * для вывода характеристик печатного издания.
 *
 * Пункт 4. Объявляет конструктор копирования
 * и оператор присваивания.
 *
 * Содержит общие характеристики печатных изданий:
 * количество страниц и издательство.
 */

#ifndef PRINTEDPUBLICATION_H
#define PRINTEDPUBLICATION_H

#include "Publication.h"

using namespace std;

/**
 * @class PrintedPublication
 * @brief Промежуточный класс печатных изданий.
 *
 * Содержит дополнительные характеристики печатной публикации.
 * От него наследуются классы Book и Magazine.
 *
 * Используется виртуальное наследование от Publication,
 * чтобы при множественном наследовании не создавать несколько
 * экземпляров базового класса.
 * В дальнейшем класс HybridBook наследуется одновременно от Book и DigitalPublication. Оба пути наследования ведут к Publication.
 * Виртуальное наследование позволяет избежать появления двух отдельных экземпляров Publication внутри одного объекта HybridBook.
 */
class PrintedPublication : virtual public Publication
{
protected:
    /** Количество страниц печатного издания. */
    int pages;

    /** Название издательства, выпустившего издание. */
    string publisher;

public:
    /**
     * @brief Создаёт новое печатное издание.
     * @param title Название издания.
     * @param isbn ISBN издания.
     * @param pages Количество страниц.
     * @param publisher Название издательства.
     *
     * Инициализирует поля базового класса Publication
     * и собственные характеристики печатного издания.
     */
    PrintedPublication(const string &title, const string &isbn,
                       int pages, const string &publisher);

    /**
     * @brief Создаёт копию печатного издания.
     * @param other Объект, данные которого копируются.
     *
     * Копирует данные базового класса и собственные поля.
     */
    PrintedPublication(const PrintedPublication &other);

    /**
     * @brief Оператор присваивания печатного издания.
     * @param other Объект, данные которого присваиваются.
     * @return Ссылка на текущий объект.
     *
     * Выполняет проверку на самоприсваивание,
     * копирует данные Publication и поля текущего класса.
     */
    PrintedPublication &operator=(const PrintedPublication &other);

    /**
     * @brief Виртуальный деструктор класса.
     *
     * Используется стандартная реализация деструктора,
     * поскольку класс не управляет динамически выделенными ресурсами.
     */
    ~PrintedPublication() override = default;

    /**
     * @brief Возвращает количество страниц издания.
     * @return Количество страниц.
     */
    int getPages() const;

    /**
     * @brief Возвращает название издательства.
     * @return Название издательства.
     */
    string getPublisher() const;

    /**
     * @brief Выводит информацию о печатном издании.
     *
     * Выводит название, ISBN, количество страниц
     * и название издательства.
     *
     * Переопределяет виртуальный метод printInfo()
     * базового класса Publication.
     */
    void printInfo() const override;
};

#endif
