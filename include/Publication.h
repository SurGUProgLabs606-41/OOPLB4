/**
 * @file Publication.h
 * @brief Объявление абстрактного базового класса Publication.
 *
 * @details
 * Класс Publication представляет общий интерфейс библиотечного издания.
 *
 * Реализует следующие требования лабораторной работы:
 *
 * Пункт 1. Начальный уровень иерархии наследования.
 *
 * Пункт 2. Абстрактный базовый класс. Содержит чисто виртуальные
 * функции getTitle(), getISBN() и printInfo().
 *
 * Пункт 3. Объявляет виртуальную функцию isDigital(),
 * которая имеет реализацию по умолчанию в Publication.cpp.
 *
 * Пункт 4. Содержит конструктор копирования и оператор присваивания.
 *
 * Пункт 5. Содержит статические поля totalCount и digitalCount,
 * а также статические методы getTotalCount(), getDigitalCount()
 * и findByISBN().
 *
 * Пункт 6. Обеспечивает полиморфную работу через указатели
 * и ссылки на базовый класс.
 *
 * Пункт 8. Объявляет дружественную функцию printPublication().
 */


#ifndef PUBLICATION_H
#define PUBLICATION_H

#include <string>

using namespace std;

/**
 * @class Publication
 * @brief Абстрактный базовый класс библиотечного издания.
 *
 * Хранит общую информацию об издании: название и ISBN.
 * Также содержит общие счётчики созданных объектов и статический
 * массив для регистрации существующих объектов.
 *
 * Класс является абстрактным, поскольку содержит чисто виртуальные
 * методы getTitle(), getISBN() и printInfo().
 */
class Publication
{
protected:
    /** Название библиотечного издания. 
    * потому что он внутри класса
    * общую информацию обо всех объектах класса publication
    */
    string title;

    /** Международный стандартный номер книги (ISBN). */
    string isbn;

    /** Общее количество существующих объектов всех типов изданий. */
    static int totalCount;

    /** Количество существующих электронных изданий. */
    static int digitalCount;

    /**
     * Массив указателей на зарегистрированные объекты изданий.
     *
     * Используется методом findByISBN() для поиска издания по ISBN.
     * Максимальная вместимость массива — 100 объектов.
     */
    static Publication *registry[100];

    /** Текущее количество объектов, зарегистрированных в массиве registry. */
    static int registryCount;

public:
    /**
     * @brief Создаёт новое библиотечное издание.
     * @param title Название издания.
     * @param isbn ISBN издания.
     *
     * Увеличивает общий счётчик объектов и регистрирует объект
     * в массиве registry, если в нём есть свободное место.
     */
    Publication(const string &title, const string &isbn);

    /**
     * @brief Создаёт копию существующего издания.
     * @param other Объект, данные которого копируются.
     *
     * Копирует название и ISBN, увеличивает общий счётчик
     * и регистрирует новый объект.
     */
    Publication(const Publication &other);

    /**
     * @brief Присваивает текущему объекту данные другого издания.
     * @param other Объект, данные которого присваиваются.
     * @return Ссылка на текущий объект.
     *
     * Выполняет проверку на самоприсваивание.
     */
    Publication &operator=(const Publication &other);

    /**
     * @brief Виртуальный деструктор базового класса.
     *
     * Удаляет указатель на текущий объект из массива registry
     * и уменьшает общий счётчик объектов.
     *
     * Виртуальность деструктора необходима для корректного
     * удаления объектов производных классов через указатель
     * на базовый класс.
     */
    virtual ~Publication();

    /**
     * @brief Возвращает название издания.
     * @return Название издания.
     *
     * Чисто виртуальный метод. Реализуется в производных классах.
     */
    virtual string getTitle() const = 0;

    /**
     * @brief Возвращает ISBN издания.
     * @return ISBN издания.
     *
     * Чисто виртуальный метод. Реализуется в производных классах.
     */
    virtual string getISBN() const = 0;

    /**
     * @brief Выводит информацию об издании.
     *
     * Чисто виртуальный метод. Каждый производный класс
     * самостоятельно определяет формат вывода информации.
     */
    virtual void printInfo() const = 0;

    /**
     * @brief Проверяет, является ли издание электронным.
     * @return false — если издание не является электронным.
     *
     * Виртуальный метод с реализацией по умолчанию.
     * В производном классе DigitalPublication переопределяется
     * для электронных изданий.
     */
    virtual bool isDigital() const;

    /**
     * @brief Возвращает общее количество существующих изданий.
     * @return Количество объектов всех типов изданий.
     */
    static int getTotalCount();

    /**
     * @brief Возвращает количество существующих электронных изданий.
     * @return Количество электронных изданий.
     */
    static int getDigitalCount();

    /**
     * @brief Выполняет поиск издания по ISBN.
     * @param isbn ISBN искомого издания.
     * @return Указатель на найденный объект или nullptr,
     *         если издание не найдено.
     *
     * Поиск выполняется среди объектов, зарегистрированных
     * в статическом массиве registry.
     */
    static Publication *findByISBN(const string &isbn);

    /**
     * @brief Дружественная функция для вывода информации об издании.
     * @param publication Объект, информацию о котором необходимо вывести.
     *
     * Функция имеет доступ к защищённым и закрытым членам класса.
     * Сам вывод выполняется через виртуальный метод printInfo().
     */
    friend void printPublication(const Publication &publication);
};

#endif
